-- 018: баунти «за голову» убрано (решение клуба 07.10.2026).
-- Весь взнос входа и ребая идёт в призовой фонд: фонд = Σ buyInRub·k по всем входам и ребаям
-- (кратность k из 015 остаётся: вход ×2 = 1 000 ₽ = 1 000 фишек, всё в фонд). Нокауты остаются
-- статистикой — журнал (кто выбил), очки, ачивки, звания, рекорды, лента, голос табло — и на деньги
-- не влияют. Деньги считает домен (replay/computeMoney), он поле bountyRub больше не знает и в
-- старых форматах молча его игнорирует: новому коду всё равно, применена ли уже эта миграция.
--
-- Старому коду — нет. Клиент, открытый на прежней сборке, считал фонд как buyInRub − bountyRub без
-- значения по умолчанию и после этой миграции показывает «NaN ₽» в фонде, призах и расчёте, а
-- старая форма админки отклоняет формат без ключа. Новый формат доходит до него без перезагрузки:
-- evenings в публикации Realtime (004), и UPDATE ниже сам рассылает изменение; табло опрашивает
-- board_state раз в 3 с. Поэтому не выкатывать во время вечера, а после деплоя перезагрузить табло
-- и открытые Mini App (DEPLOY.md, «Обновления»). И второе: вечера, сыгранные по старым правилам до
-- деплоя, новый домен пересчитывает без баунти — перед деплоем проверить, есть ли такие
-- (ARCHITECTURE.md, «Баунти убрано»; DEPLOY.md).
--
-- SQL-функции bountyRub не читали и не пишут: add_event и add_guest (015/017) проверяют только форму
-- payload, board_state и set_payout отдают и правят формат вечера как есть, voice_manifest_input
-- берёт форматы целиком. Их тела не меняются.
--
-- Здесь — только данные: ключ bountyRub вычищается из конфигов форматов (formats.config, в том числе
-- клубного формата, который заводит миграция 011) и из снимков формата вечеров (evenings.format) в
-- любом статусе. Остальные ключи не трогаются. Повторный прогон ничего не меняет.
-- Новых объектов нет — грантов не нужно.

update public.formats
set config = config - 'bountyRub'
where config ? 'bountyRub';

-- Снимок формата у вечера в любом статусе: и у будущих (анонс, табло, cron-tick), и у сыгранных.
-- Триггер evenings_scoring_snapshot (013) у завершённых вечеров снимок очков сохраняет.
update public.evenings
set format = format - 'bountyRub'
where format ? 'bountyRub';
